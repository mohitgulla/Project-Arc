def _sessions(n: int, start: dt.date = dt.date(2020, 1, 2)) -> list[dt.date]:
    out, d = [], start
    while len(out) < n:
        if d.weekday() < 5:
            out.append(d)
        d += dt.timedelta(days=1)
    return out


def _px(days: list[dt.date], seed: int) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    c = 100 * np.exp(np.cumsum(rng.normal(0.0003, 0.012, len(days))))
    o = c * (1 + rng.normal(0, 0.004, len(days)))
    return pd.DataFrame({"open": o, "high": c * 1.01, "low": c * 0.99, "close": c}, index=days)


def _opt(days: list[dt.date], seed: int) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    df = pd.DataFrame(index=days)
    for c in lf.OPTION_COLS:
        df[c] = rng.uniform(0.05, 0.6, len(days))
    df["d9_pass"] = rng.random(len(days)) > 0.3
    return df


def _trades(days: list[dt.date]) -> pd.DataFrame:
    rows = []
    spec = [
        ("AAA", "bull_put", 300),
        ("BBB", "bear_call", 300),
        ("AAA", "iron_condor", 320),
        ("SPY", "long_call", 340),
        ("BBB", "bull_put", 345),
        ("XLK", "bear_call", 352),
    ]
    for i, (u, k, j) in enumerate(spec):
        d = days[j]
        rows.append(
            {
                "underlying": u,
                "kind": k,
                "spec": f"{k}_d{20 + i}_w2_dte30-45",
                "entry_date": d,
                "exit_date": d + dt.timedelta(days=14),
                "exit_day": d + dt.timedelta(days=14),
                "expiration": d + dt.timedelta(days=40),
                "contracts": 2,
                "pnl": [-300.0, 120.0, 80.0, -50.0, 40.0, 10.0][i],
                "pnl_mid": [-250.0, 140.0, 100.0, -30.0, 60.0, 20.0][i],
                "pnl_unit": [-150.0, 60.0, 40.0, -25.0, 20.0, 5.0][i],
                "max_loss_unit": 200.0,
                "entry_net": -0.9,
                "entry_net_mid": -1.0,
                "credit_width": 2.0 if k != "long_call" else np.nan,
                "debit_width": np.nan if k != "long_call" else 1.0,
                "etf": u in ("SPY", "XLK"),
                "risk": 400.0,
                "direction": {"bull_put": "bullish", "bear_call": "bearish"}.get(k, "neutral"),
                "legs": f"+{u}{i}",
            }
        )
    return pd.DataFrame(rows)


def build_world() -> dict[str, object]:
    days = _sessions(420)
    prices = {
        t: _px(days, s)
        for t, s in (("AAA", 1), ("BBB", 2), ("SPY", 3), ("HYG", 4), ("TLT", 5), ("XLK", 6))
    }
    opt = {t: _opt(days, s) for t, s in (("AAA", 7), ("BBB", 8), ("SPY", 9), ("XLK", 10))}
    earnings = pd.DataFrame(
        {
            "ticker": ["AAA", "AAA", "BBB", "BBB"],
            "event_date": [days[250], days[310], days[200], days[347]],
            "implied_move": [0.05, 0.06, 0.04, 0.07],
            "realised_move": [0.02, 0.09, 0.03, 0.01],
        }
    )
    macro = {"fomc": [days[301], days[380]], "cpi": [days[330]], "nfp": [days[346]]}
    equity = pd.Series(25_000.0 + 40 * np.sin(np.arange(len(days)) / 9.0), index=days)
    return {
        "days": days,
        "prices": prices,
        "opt": opt,
        "earnings": earnings,
        "macro": macro,
        "equity": equity,
        "trades": _trades(days),
    }


def _jsonable(v: object) -> object:
    if isinstance(v, (bool, np.bool_)):
        return bool(v)
    if isinstance(v, (int, np.integer)):
        return int(v)
    if isinstance(v, (float, np.floating)):
        f = float(v)
        return None if math.isnan(f) else ("inf" if math.isinf(f) else f)
    if v is None or v is pd.NA or v is pd.NaT:
        return None
    if isinstance(v, (dt.date, pd.Timestamp)):
        return str(v)
    return str(v)


def _table(df: pd.DataFrame) -> dict[str, object]:
    return {
        "columns": [str(c) for c in df.columns],
        "index": [_jsonable(i) for i in df.index],
        "rows": [[_jsonable(v) for v in r] for r in df.itertuples(index=False)],
    }


def snapshot() -> dict[str, object]:
    w = build_world()
    prices, opt = w["prices"], w["opt"]
    market = lf.market_state(prices, opt, ["AAA", "BBB", "SPY", "XLK"])  # type: ignore[arg-type]
    feats = lf.build_features(
        w["trades"],  # type: ignore[arg-type]
        w["equity"],  # type: ignore[arg-type]
        prices=prices,  # type: ignore[arg-type]
        opt=opt,  # type: ignore[arg-type]
        market=market,
        earnings=w["earnings"],  # type: ignore[arg-type]
        macro=w["macro"],  # type: ignore[arg-type]
        groups={"AAA": "technology", "BBB": "health", "SPY": "etf:broad_equity"},
    )
    chg = lf.regime_change_soon(market)
    pstate = lf.price_state(prices["AAA"])  # type: ignore[index]
    return {
        "features": _table(feats),
        "market": _table(market.iloc[::7]),
        "price_state": _table(pstate.iloc[::11]),
        "regime_change": [bool(x) for x in chg.iloc[::5]],
        "etf_class": [
            lf.etf_class("X", n)
            for n in ("ProShares UltraPro QQQ", "SPDR Gold Trust", "iShares Core Bond", "Foo")
        ],
        "sic": [lf.sic_sector(s) for s in (None, 3571, 2834, 6021, 6512, 4911, 1311, 9999)],
    }


def test_loss_anatomy_feature_table_matches_pre_promotion_golden() -> None:
    got = json.loads(json.dumps(snapshot()))
    if os.environ.get("ARC_REGEN_GOLDEN") == "1":  # pragma: no cover - manual regen
        GOLDEN.write_text(json.dumps(got, indent=0, sort_keys=False) + "\n")
    want = json.loads(GOLDEN.read_text())
    assert_json_close(got, want)


def test_script_reuses_the_promoted_formulas() -> None:
    """Promote, don't copy: the script's formulas *are* arc.ml.features.compute's."""
    from arc.ml.features import compute

    for name in (
        "etf_class",
        "sic_sector",
        "price_state",
        "market_state",
        "event_features",
        "portfolio_state",
        "build_features",
        "regime_change_soon",
        "trade_columns",
    ):
        assert getattr(lf, name) is getattr(compute, name), name
