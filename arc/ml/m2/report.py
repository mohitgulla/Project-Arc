"""M2 model cards and the research doc (E27.3): aggregates only (D84 licence).

Both render from a trained version directory (``manifest.json``, ``eval_*.csv``,
``holdout_*.csv``), so ``docs/RESEARCH/models/<family>-<version>.md`` and
``docs/RESEARCH/ml-m2.md`` regenerate without retraining:
``arc ml m2 report --version credit/<v> --version debit/<v>``.
"""

from __future__ import annotations

import json
from typing import TYPE_CHECKING, Any

import pandas as pd

from arc.ml.m1.report import _md
from arc.ml.registry import holdout_reads, load_index

if TYPE_CHECKING:
    from collections.abc import Sequence
    from pathlib import Path

PROB_COLS = [
    "win_log_loss",
    "win_log_loss_logistic",
    "win_log_loss_managed_pop",
    "win_log_loss_raw",
    "win_brier",
    "win_ece",
    "win_ece_raw",
    "win_auc",
    "stop_log_loss",
    "stop_log_loss_logistic",
    "stop_ece",
    "stop_auc",
]
RANK_COLS = [
    "er_ic_mean",
    "er_ic_nw_t",
    "er_decile_spread",
    "ic_managed_net_ev",
    "ic_rorc_day",
    "ic_credit_width",
    "ic_debit_width",
    "ic_ev_proxy",
    "er_mix_gap",
    "q10_90_cover",
]


def _csv(vdir: Path, name: str) -> pd.DataFrame | None:
    p = vdir / f"{name}.csv"
    return pd.read_csv(p) if p.is_file() else None


def _cols(df: pd.DataFrame, cols: Sequence[str]) -> list[str]:
    return [c for c in cols if c in df.columns]


def _load(vdir: Path) -> dict[str, Any]:
    out: dict[str, Any] = {"manifest": json.loads((vdir / "manifest.json").read_text())}
    for n in (
        "eval_metrics",
        "eval_checks",
        "eval_rule",
        "eval_replay",
        "eval_reliability",
        "eval_regimes",
        "eval_configs_tried",
        "eval_permutation",
        "eval_gain",
        "eval_pdp",
        "holdout_metrics",
        "holdout_reliability",
        "holdout_replay",
    ):
        out[n] = _csv(vdir, n)
    p = vdir / "eval_calibration.json"
    out["calibration"] = json.loads(p.read_text()) if p.is_file() else {}
    return out


def rule_table(rule: pd.DataFrame) -> str:
    t = rule.copy()
    cols = _cols(
        t,
        [
            "fold",
            "ll_m2",
            "ll_logistic",
            "ll_managed_pop",
            "beats_logistic",
            "beats_managed_pop",
            "er_ic",
            "er_ic_t",
            "ic_pass",
            "net_incumbent",
            "net_ml_er",
            "dd_incumbent",
            "dd_ml_er",
            "replay_pass",
            "year_pass",
        ],
    )
    return _md(t[cols])


def replay_table(rep: pd.DataFrame) -> str:
    cols = _cols(
        rep,
        [
            "year",
            "use",
            "trades",
            "net_pnl",
            "max_dd_pct",
            "return_pct",
            "win_rate",
            "net_per_risk",
            "score_coverage",
            "net_stocks",
            "net_etfs",
        ],
    )
    return _md(rep[cols], ".2f")


def render_card(vdir: Path, root: Path) -> str:
    d = _load(vdir)
    m = d["manifest"]
    fam = m["family"]
    idx = load_index(root, fam)
    entry = idx.versions.get(m["version"])
    met = d["eval_metrics"]
    w = []
    w.append(f"# M2 model card · {fam} · `{m['version']}`\n")
    w.append(
        "Generated by `arc ml m2 report` from `data/ml/models/{fam}/{ver}/` (aggregates only, "
        "D84). Plan ref D126/D133, card E27.3.\n".format(fam=fam, ver=m["version"])
    )
    w.append("## Identity\n")
    tw, cw = m["train_window"], m["calibration_window"]
    rows = [
        ("family / ledger profile", f"{fam} / {m['profile']}"),
        ("registry status", entry.status if entry else "unregistered"),
        ("decision rule", m["rule"]),
        ("m2_promote (dev)", "PASSED" if m.get("rule_passed") else "failed"),
        ("feature schema", m["feature_schema"]),
        (
            "M1 version (features used?)",
            f"{m.get('m1_version')} ({'yes' if m.get('m1_features_used') else 'no'})",
        ),
        ("label slippage", m["label_slippage"]),
        (
            "train window",
            f"{tw['start']} → {tw['end']} (dev; rows whose label crosses 2024 dropped)",
        ),
        ("calibration window", f"{cw['start']} → {cw['end']} ({cw['source']})"),
        (
            "rows used / ledger rows represented",
            f"{m['n_rows']:,} / {m.get('n_raw_ledger_rows', m['n_rows']):,}",
        ),
        (
            "Σ weights / n_eff (Kish)",
            f"{m.get('sum_weights', m['n_rows']):,.0f} / {m['n_eff']:,.0f}",
        ),
        ("per-day cap", str(m.get("n_raw_rows_per_day_cap"))),
        ("configs tried", str(m["configs_tried"])),
        (
            "code sha / config digest / data digest",
            f"{m['code_sha'][:12]} / {m['config_digest']} / {m['data_digest']}",
        ),
        (
            "train time / peak RSS",
            f"{m['timings']['total_s']:.0f} s / {m['timings']['peak_rss_mb']:.0f} MB",
        ),
        ("τ (p_stop filter)", f"{m['tau_stop']:.4f}"),
        (
            "holdout reads",
            str(m.get("holdout_reads", 0))
            + (
                f" ({m.get('holdout_read_at')}, sha {str(m.get('holdout_read_sha'))[:12]})"
                if m.get("holdout_reads")
                else ""
            ),
        ),
    ]
    w.append(_md(pd.DataFrame(rows, columns=["field", "value"])) + "\n")
    w.append("## Selected hyper-parameters (inner fold of the last test year)\n")
    pts = pd.DataFrame(
        [{"target": t, **p, "rounds": m["rounds"][t]} for t, p in sorted(m["points"].items())]
    )
    w.append(_md(pts) + "\n")
    if met is not None:
        a = met[(met.group == "all")]
        w.append("## Probabilistic metrics (test folds; All / Stocks / ETFs)\n")
        w.append(_md(a[["fold", "split", "n", *_cols(a, PROB_COLS)]]) + "\n")
        w.append("## Ranking metrics (per-day IC of e_r vs realised r_net; incumbent keys)\n")
        w.append(
            _md(a[["fold", "split", *_cols(a, RANK_COLS + ["er_ic_mean_alt_monotone"])]]) + "\n"
        )
        g = met[(met.split == "All") & (met.group != "all")]
        if len(g):
            w.append("## By kind and sleeve (All split)\n")
            w.append(
                _md(
                    g[
                        [
                            "fold",
                            "group",
                            "value",
                            "n",
                            *_cols(
                                g,
                                [
                                    "win_log_loss",
                                    "win_log_loss_logistic",
                                    "win_ece",
                                    "er_ic_mean",
                                    "er_ic_nw_t",
                                    "er_mean_pred",
                                    "r_mean_real",
                                ],
                            ),
                        ]
                    ]
                )
                + "\n"
            )
    if d["eval_rule"] is not None:
        w.append("## Pre-registered promote rule (m2_promote, dev)\n")
        w.append(rule_table(d["eval_rule"]) + "\n")
    if d["eval_replay"] is not None:
        w.append("## Decision-value replays (dev test years, research replays, D121)\n")
        w.append(replay_table(d["eval_replay"]) + "\n")
    rel = d["eval_reliability"]
    if rel is not None:
        w.append("## Reliability (All split, calibrated)\n")
        r = rel[rel.split == "All"]
        w.append(
            _md(r[_cols(r, ["fold", "target", "bin", "n", "weight", "mean_p", "observed"])]) + "\n"
        )
    cal = d["calibration"]
    if cal:
        w.append("## Calibration per kind (ECE under the family map; kind map when > 2× family)\n")
        rows = []
        for fold, tg in cal.items():
            for t, kinds in tg.items():
                for k, v in kinds.items():
                    rows.append({"fold": fold, "target": t, "kind": k, **v})
        w.append(_md(pd.DataFrame(rows)) + "\n")
    gain = d["eval_gain"]
    if gain is not None:
        w.append("## Top features (final model, gain share)\n")
        top = gain.pivot_table(index="feature", columns="target", values="gain_share").fillna(0.0)
        top["sum"] = top.get("win", 0) + top.get("r", 0)
        top = top.sort_values("sum", ascending=False).head(20).reset_index()
        w.append(_md(top[_cols(top, ["feature", "win", "stop", "r", "q50", "days"])]) + "\n")
    perm = d["eval_permutation"]
    if perm is not None:
        w.append("## Permutation importance (test folds)\n")
        w.append(_md(perm.sort_values(["fold", "win_ll_rise"], ascending=[True, False])) + "\n")
    pdp = d["eval_pdp"]
    if pdp is not None:
        w.append("## Partial dependence, top 8 (final model on the 2023 rows)\n")
        w.append(_md(pdp) + "\n")
    reg = d["eval_regimes"]
    if reg is not None and len(reg):
        w.append("## Regimes (known failure regimes = IC ≤ 0 or |bias| > 0.05)\n")
        rr = reg.copy()
        rr["flag"] = ((rr.er_ic <= 0) | (rr.er_bias.abs() > 0.05)).map({True: "⚠", False: ""})  # noqa: PLR2004
        w.append(_md(rr) + "\n")
    tried = d["eval_configs_tried"]
    if tried is not None:
        w.append(f"## Every configuration tried ({len(tried)})\n")
        w.append(_md(tried) + "\n")
    w.append("## Holdout\n")
    reads = [r for r in holdout_reads(root, fam) if r.get("version") == m["version"]]
    if not reads:
        w.append("Not read. The dev decision above is committed before any holdout read (D126).\n")
    else:
        w.append(_md(pd.DataFrame(reads)) + "\n")
        hm = d["holdout_metrics"]
        if hm is not None:
            a = hm[hm.group == "all"]
            w.append(_md(a[["split", "n", *_cols(a, PROB_COLS + RANK_COLS)]]) + "\n")
        if d["holdout_replay"] is not None:
            w.append(replay_table(d["holdout_replay"]) + "\n")
    return "\n".join(w)


def render_doc(root: Path, vdirs: Sequence[Path], extra: str = "") -> str:
    w = ["# M2 · calibrated candidate outcome model (E27.3, D126)\n"]
    w.append(
        "Generated by `arc ml m2 report` from the registered versions below; aggregates only "
        "(D84). The model cards (`docs/RESEARCH/models/`) carry every table.\n"
    )
    w.append("## Promote-rule result (m2_promote, dev 2022 + 2023)\n")
    for vd in vdirs:
        d = _load(vd)
        m = d["manifest"]
        verdict = "PASSED → shadow" if m.get("rule_passed") else "failed → candidate"
        w.append(f"### {m['family']} · `{m['version']}` · {verdict}\n")
        if d["eval_rule"] is not None:
            w.append(rule_table(d["eval_rule"]) + "\n")
        if d["eval_replay"] is not None:
            w.append(
                "Decision-value replays (incumbent = `managed_net_ev`; `ml_er` = rank by e_r; "
                "`ml_er_pos` = skip e_r ≤ 0; `ml_pstop` = skip p_stop ≥ τ):\n"
            )
            w.append(replay_table(d["eval_replay"]) + "\n")
        met = d["eval_metrics"]
        if met is not None:
            a = met[met.group == "all"]
            w.append(
                _md(
                    a[
                        [
                            "fold",
                            "split",
                            "n",
                            *_cols(
                                a,
                                [
                                    "win_log_loss",
                                    "win_log_loss_logistic",
                                    "win_log_loss_managed_pop",
                                    "win_ece",
                                    "er_ic_mean",
                                    "er_ic_nw_t",
                                    "er_decile_spread",
                                    "ic_managed_net_ev",
                                ],
                            ),
                        ]
                    ]
                )
                + "\n"
            )
        tm = m["timings"]
        w.append(
            f"Train {tm['total_s']:.0f} s, peak RSS {tm['peak_rss_mb']:.0f} MB, "
            f"{m['n_rows']:,} rows (n_eff {m['n_eff']:,.0f}), "
            f"{m['configs_tried']} configurations.\n"
        )
    if extra:
        w.append(extra.rstrip() + "\n")
    return "\n".join(w)


def write_reports(
    root: Path,
    pairs: Sequence[tuple[str, ...]],
    *,
    doc: Path,
    cards: Path,
    extra: Path | None = None,
) -> list[Path]:
    cards.mkdir(parents=True, exist_ok=True)
    out = []
    vdirs = []
    for fam, ver in pairs:
        vd = root / fam / ver
        vdirs.append(vd)
        p = cards / f"{fam}-{ver}.md"
        p.write_text(render_card(vd, root))
        out.append(p)
    doc.write_text(render_doc(root, vdirs, extra.read_text() if extra else ""))
    out.append(doc)
    return out
