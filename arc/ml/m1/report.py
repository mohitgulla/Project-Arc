"""M1 research report and model card (E27.2): aggregates only (D84 licence).

Both render from a trained version directory (``manifest.json``, ``eval_*.csv``,
``timings.json``), so the committed ``docs/RESEARCH/ml-m1.md`` regenerates from the
artefacts without retraining: ``arc ml m1 report --model data/ml/models/m1/<version>``.
"""

from __future__ import annotations

import json
from typing import TYPE_CHECKING

import pandas as pd

from arc.ml.features.compute import M1_QUANTILES, qtag
from arc.ml.m1.predict import M1Manifest

if TYPE_CHECKING:
    from pathlib import Path

    import numpy as np


def _md(df: pd.DataFrame, floatfmt: str = ".4f") -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        cells = []
        for v in row:
            if isinstance(v, float):
                cells.append("" if v != v else format(v, floatfmt))  # noqa: PLR0124 - NaN
            else:
                cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def _load(vdir: Path) -> dict[str, object]:
    out: dict[str, object] = {
        "manifest": M1Manifest.model_validate_json((vdir / "manifest.json").read_text()),
        "timings": json.loads((vdir / "timings.json").read_text()),
    }
    for name in ("metrics", "decisions", "regimes", "gain", "permutation", "others", "crossing"):
        out[name] = pd.read_csv(vdir / f"eval_{name}.csv")
    return out


def _pct(x: float | np.floating) -> str:
    return f"{100 * float(x):.1f}"


def metric_section(m: pd.DataFrame, kind: str) -> str:
    parts = []
    for h in sorted(m.h.unique()):
        t = m[(m.kind == kind) & (m.h == h)].copy()
        if t.empty:
            continue
        cols = ["fold", "split", "model", "n", "pinball", "crps", "dm_stat", "dm_p_one_sided"]
        cols += ["cov_err_raw", "cov_err_cal", "cov_err"]
        cols += ["sign_acc", "rank_ic"] if kind == "log_ret" else ["qlike", "rank_ic"]
        t = t[[c for c in cols if c in t.columns]]
        for c in ("cov_err", "cov_err_raw", "cov_err_cal", "sign_acc"):
            if c in t:
                t[c] = t[c].map(lambda v: "" if v != v else _pct(v))  # noqa: PLR0124
        parts.append(f"#### {kind} h{h}\n\n" + _md(t))
    return "\n\n".join(parts)


def coverage_section(m: pd.DataFrame) -> str:
    cols = [f"cov_{qtag(p)}" for p in M1_QUANTILES]
    t = m[m.model.isin(["lgbm", "baseline", "iv_lognormal"]) & m[cols[0]].notna()]
    t = t[["fold", "kind", "h", "split", "model", *cols]].copy()
    for c in cols:
        t[c] = t[c].map(_pct)
    nominal = " / ".join(_pct(p) for p in M1_QUANTILES)
    return f"Nominal: {nominal} (empirical P(y ≤ q_p), %; after CQR).\n\n" + _md(t)


def render_report(vdir: Path) -> str:
    d = _load(vdir)
    man: M1Manifest = d["manifest"]  # type: ignore[assignment]
    tm: dict = d["timings"]  # type: ignore[assignment]
    m: pd.DataFrame = d["metrics"]  # type: ignore[assignment]
    dec: pd.DataFrame = d["decisions"]  # type: ignore[assignment]
    reg: pd.DataFrame = d["regimes"]  # type: ignore[assignment]
    gain: pd.DataFrame = d["gain"]  # type: ignore[assignment]
    perm: pd.DataFrame = d["permutation"]  # type: ignore[assignment]
    oth: pd.DataFrame = d["others"]  # type: ignore[assignment]
    cr: pd.DataFrame = d["crossing"]  # type: ignore[assignment]
    w = []
    w.append("# M1: per-ticker move & volatility distribution forecast (E27.2, D126)\n")
    w.append(
        f"Generated by `arc ml m1 report --model data/ml/models/m1/{man.version}` from the "
        "run's aggregates. Dev data only (2020-01 → 2023-12, D84); the holdout was not read. "
        f"Feature schema `{man.feature_schema}`, data digest `{man.data_digest}`, code "
        f"`{man.code_sha[:10]}`, {tm['rows']['dataset']:,} rows over "
        f"{tm['rows']['tickers']} tickers.\n"
    )
    w.append("## Keep / ship decision per target (pre-registered rule)\n")
    w.append(
        "LightGBM ships for a target only if, in **both** test years (2022, 2023), its "
        "calibrated pinball loss beats the baseline with a one-sided Diebold-Mariano p < "
        "0.05 (per-day cross-sectional mean differential, Newey-West h − 1 lags) **and** "
        "its post-CQR coverage error (max |empirical − nominal| over the 7 levels) is "
        "≤ 3 points. Baseline = historical quantiles for `log_ret_h` (IV lognormal where "
        "the history is short), HAR-IV for `rv_h`.\n"
    )
    w.append(_md(dec))
    w.append("\n## Metrics per horizon vs the baselines\n")
    w.append(
        "`pinball` = mean quantile loss over the 7 levels (target units: log return or "
        "annualised vol); `crps` ≈ 2 × mean pinball on the grid; `dm_stat` < 0 means the "
        "model beats the baseline; `cov_err_raw` / `cov_err` = coverage error in points "
        "on the test year before / after CQR; `cov_err_cal` = the same after CQR on the "
        "calibration block itself (in-sample for the offsets: ≈ 0 by construction, so the "
        "gap to `cov_err` measures drift between the calibration block and the test year); "
        "`rank_ic` = mean per-day Spearman of the median vs the "
        "outcome. All / Stocks / ETFs per the owner rule.\n"
    )
    w.append("### log_ret_h\n")
    w.append(metric_section(m, "log_ret"))
    w.append("\n### rv_h\n")
    w.append(metric_section(m, "rv"))
    pts = m[m.model.isin(["har_point", "iv30_point"])][["fold", "h", "split", "model", "qlike"]]
    w.append("\nQLIKE of the point forecasts for reference (HAR-RV, IV30):\n")
    w.append(_md(pts))
    w.append("\n## Coverage tables\n")
    w.append(coverage_section(m))
    if "cov_err_roll" in m.columns:
        w.append("\n## Diagnostic: monthly rolling CQR (post-hoc, not the keep rule)\n")
        w.append(
            "The pre-registered CQR fits offsets once, on the 252 sessions before each test "
            "year; drift between that block and the test year shows as `cov_err` far above "
            "`cov_err_cal`. This diagnostic refits the offsets at the start of every test "
            "month on the last 252 sessions of out-of-sample predictions whose labels end "
            "before the month (purge h + 5), i.e. what a nightly live offset refresh would "
            "hold. It is reported for the record only; the shipped decision above does not "
            "use it, and changing the protocol to it needs a new pre-registration.\n"
        )
        cols = ["fold", "kind", "h", "model", "pinball", "pinball_roll", "cov_err", "cov_err_roll"]
        r = m[(m.split == "All") & m.model.isin(["lgbm", "baseline"])][cols].copy()
        for c in ("cov_err", "cov_err_roll"):
            r[c] = r[c].map(_pct)
        w.append(_md(r))
    w.append("\n## Quantile crossing before sorting (LightGBM)\n")
    w.append(_md(cr))
    w.append("\n## Excursions and move-vs-implied (shipped log-return model)\n")
    w.append(
        "Rank IC of the M1-implied quantities against the other targets: the expected "
        "|move| ÷ implied vs `move_vs_implied_h`, and the q95 − q50 / q50 − q05 widths "
        "(in IV units) vs `max_up_h` / `max_dn_h`. Mean forecast vs realised "
        "move-vs-implied checks the level.\n"
    )
    w.append(_md(oth))
    w.append("\n## Feature importance\n")
    g = gain[gain.h == 21].sort_values(["kind", "gain"], ascending=[True, False])
    g = g.groupby("kind").head(15)
    w.append("Gain share (final model, h21, summed over the 7 quantile models):\n")
    w.append(_md(g, ".3f"))
    w.append(
        "\nPermutation importance on the test years (h21; rise in standardised pinball "
        "when the feature is shuffled; top-15-by-gain candidates, 40k sampled rows):\n"
    )
    p = perm.sort_values(
        ["fold", "kind", "level", "pinball_rise"], ascending=[True, True, True, False]
    )
    w.append(_md(p.groupby(["fold", "kind", "level"]).head(5), ".5f"))
    w.append("\n## Top failure regimes (LightGBM vs baseline)\n")
    w.append(
        "Regimes: SPY v2 trend, SPY IV percentile (VIX proxy: high ≥ 0.8, low ≤ 0.2), an "
        "earnings reaction inside the horizon, Stock vs ETF. Sorted by the pinball "
        "difference vs the baseline (positive = LightGBM worse) and by coverage error.\n"
    )
    worst = reg.sort_values("pinball_vs_base", ascending=False).head(12)
    w.append(_md(worst, ".5f"))
    w.append("\nWorst coverage after CQR:\n")
    w.append(_md(reg.sort_values("cov_err", ascending=False).head(12), ".4f"))
    w.append("\n## Cost\n")
    sz = sum(tm["sizes"].values())
    w.append(
        f"- Train (walk-forward, 2 folds × calibration + test models): "
        f"{tm['fold_fits_s']:.0f} s; final fit {tm['final_fit_s']:.0f} s; whole run "
        f"{tm['total_s']:.0f} s ({man.lgb_params.get('num_threads')} threads, "
        f"{man.num_rounds} rounds).\n"
        f"- Predict one session ({int(tm['predict_one_day_rows'])} names; shipped model = "
        f"baselines + conformal + published features, incl. loading the artefact): "
        f"{tm['predict_one_day_s']:.2f} s, the nightly C500 cost. The all-LightGBM path "
        f"(56 boosters) takes {tm.get('predict_one_day_all_lgbm_s', float('nan')):.2f} s.\n"
        f"- Model size: {len(tm['sizes'])} LightGBM text dumps, {sz / 1e6:.1f} MB total "
        f"(written for every target so a later version can switch without retraining).\n"
    )
    return "\n".join(w) + "\n"


def render_card(vdir: Path) -> str:
    d = _load(vdir)
    man: M1Manifest = d["manifest"]  # type: ignore[assignment]
    dec: pd.DataFrame = d["decisions"]  # type: ignore[assignment]
    tm: dict = d["timings"]  # type: ignore[assignment]
    lines = [
        f"# Model card: {man.version}",
        "",
        "M1 (E27.2, D126): calibrated quantiles of the h-session log return and realised vol, "
        "h in {5, 10, 21, 42} sessions. Never a gate input.",
        "",
        f"- Feature schema: `{man.feature_schema}` ({len(man.features)} live features)",
        f"- Data digest: `{man.data_digest}`; code sha `{man.code_sha}`",
        f"- Config hashes: {json.dumps(man.config_hashes, sort_keys=True)}",
        f"- Train window: {json.dumps(man.train_window, sort_keys=True)}",
        f"- Calibration: {json.dumps(man.calibration_window, sort_keys=True)}",
        f"- LightGBM: {man.num_rounds} rounds, params {json.dumps(man.lgb_params, sort_keys=True)}",
        f"- Rows: {tm['rows']['dataset']:,}; tickers {tm['rows']['tickers']}",
        "- Holdout: not read (dev only).",
        "",
        "## Shipped source per target",
        "",
        _md(dec[["kind", "h", "source"]]),
        "",
        "Artefacts: `lgbm/*.txt` (LightGBM text dumps, sha256 in `manifest.json`), "
        "`manifest.json` (targets, conformal offsets, HAR-IV coefficients), "
        "`features.json`, `FEATURE_SCHEMA_VERSION`, `eval_*.csv`, "
        "`oos_m1_features.parquet` (out-of-sample m1 features for 2022 and 2023).",
    ]
    return "\n".join(lines) + "\n"
